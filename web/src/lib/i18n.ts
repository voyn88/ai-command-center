export const LANG_KEY = 'aicc-lang'

export function initialLang(): 'ru' | 'en' {
  try {
    const saved = window.localStorage.getItem(LANG_KEY)
    if (saved === 'ru' || saved === 'en') return saved
  } catch {
    // storage unavailable (private mode etc.) - fall back to Russian
  }
  return 'ru'
}

i18n
  .use(initReactI18next)
  .init({
    resources: {
      en: { translation: en },
      ru: { translation: ru },
    },
    lng: initialLang(),
    fallbackLng: 'en',
    interpolation: { escapeValue: false },
  })

function syncDocumentLang(lng: string) {
  if (typeof document !== 'undefined') document.documentElement.lang = lng
}
syncDocumentLang(i18n.language)
i18n.on('languageChanged', syncDocumentLang)

export function toggleLang() {
  const next = i18n.language === 'en' ? 'ru' : 'en'
  try {
    window.localStorage.setItem(LANG_KEY, next)
  } catch {
    // ignore: the choice just will not survive a reload
  }
  i18n.changeLanguage(next)
}

export default i18n
